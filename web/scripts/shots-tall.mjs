// Tall screenshots of the device page sections (overview with auto profile, rapid fire editor).
import puppeteer from 'puppeteer-core'
const out = process.argv[2]
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', defaultViewport: { width: 1080, height: 1150 } })
const page = await browser.newPage()
const click = (text) => page.evaluate((t) => [...document.querySelectorAll('button')].find((b) => b.textContent.includes(t))?.click(), text)
await page.goto('http://localhost:4173/index.html?lang=tr&v=a#device=ModelOWireless/overview', { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 1200))
await page.screenshot({ path: `${out}/p-auto.png` })
await page.goto('http://localhost:4173/index.html?lang=tr&v=b#device=ModelOWireless/buttons', { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 900))
await click('İleri (öndeki yan tuş)')
await new Promise((r) => setTimeout(r, 600))
await page.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Makro')?.click())
await new Promise((r) => setTimeout(r, 400))
await click('Hızlı tıklama')
await new Promise((r) => setTimeout(r, 500))
await page.screenshot({ path: `${out}/p-rapid.png` })
await page.goto('http://localhost:4173/index.html?lang=tr&v=d#device=ModelOWireless/macros', { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 700))
await click('Hızlı tıklama')
await new Promise((r) => setTimeout(r, 700))
await page.screenshot({ path: `${out}/p-macro.png` })
await page.goto('http://localhost:4173/index.html?lang=tr&v=c#about', { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 900))
await page.screenshot({ path: `${out}/p-about.png` })
await browser.close()
